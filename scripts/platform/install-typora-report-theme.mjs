import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const genericStylePath = path.join(repositoryDirectory, 'docs', 'generic-typora-report.css');
const themesDirectory = process.env.TYPORA_THEMES_DIRECTORY || path.join(process.env.APPDATA || '', 'Typora', 'themes');
const baseThemeName = process.argv[2] || 'github.css';
const targetThemeName = process.argv[3] || 'rsscomposer-report.css';
const baseThemePath = path.join(themesDirectory, baseThemeName);
const targetThemePath = path.join(themesDirectory, targetThemeName);

if (!fs.existsSync(genericStylePath)) throw new Error(`Generic Typora style is missing: ${genericStylePath}`);
if (!fs.existsSync(baseThemePath)) throw new Error(`Typora base theme is missing: ${baseThemePath}`);

const baseTheme = fs.readFileSync(baseThemePath, 'utf8');
const genericStyle = fs.readFileSync(genericStylePath, 'utf8');
const output = [
  '/* Generated by automated-testing. Base theme is preserved above; report overrides are appended below. */',
  baseTheme.trimEnd(),
  '',
  '/* BEGIN RSSComposer report presentation overrides */',
  genericStyle.trim(),
  '/* END RSSComposer report presentation overrides */',
  '',
].join('\n');

fs.mkdirSync(themesDirectory, { recursive: true });
fs.writeFileSync(targetThemePath, output, 'utf8');
process.stdout.write(`${JSON.stringify({ BaseThemePath: baseThemePath, TargetThemePath: targetThemePath, GenericStylePath: genericStylePath, Encoding: 'UTF-8' }, null, 2)}\n`);
